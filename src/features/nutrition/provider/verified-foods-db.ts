export function searchVerifiedFoods(query: string): FoodSearchResult[] {
  const normalizedQuery = query.toLowerCase().trim();
  if (!normalizedQuery) return [];

  const tokens = normalizedQuery.split(/\s+/);

  return VERIFIED_FOODS.filter((food) => {
    const searchable = `${food.name} ${food.description} ${food.preparationState || ''}`.toLowerCase();
    return tokens.every((token) => searchable.includes(token));
  }).map((food) => ({
    id: food.id,
    name: food.name,
    description: food.description,
    provider: food.provider,
    preparationState: food.preparationState,
    nutrientsAvailableCount: Object.values(food.nutrientsPerReference).filter((n) => n.isAvailable).length,
  }));
}

export function getVerifiedFoodById(id: string): FoodDetail | undefined {
  return VERIFIED_FOODS.find((f) => f.id === id);
}
